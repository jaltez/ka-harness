    #[test]
    fn seatbelt_profile_shapes() {
        // write allowlist, read-everything default, network denied
        let policy = Policy::Fs {
            allow_write: vec![PathBuf::from("/work/proj"), PathBuf::from("/tmp/x")],
            allow_net: false,
            pass_env: Vec::new(),
            net: NetDomains::default(),
        };
        let profile = seatbelt_profile(&policy);
        assert!(profile.contains("(version 1)"), "{profile}");
        assert!(profile.contains("(allow default)"), "{profile}");
        assert!(profile.contains("(allow file-read*)"), "{profile}");
        assert!(
            profile.contains("(allow file-write* (subpath \"/work/proj\") (subpath \"/tmp/x\")"),
            "explicit allow documents the granted trees (the enumerated /dev \
             surface follows): {profile}"
        );
        assert!(
            profile.contains(
                "(deny file-write* (require-all (require-not (subpath \"/work/proj\")) \
                 (require-not (subpath \"/tmp/x\"))"
            ),
            "deny wins in SBPL; require-all is the real AND — sibling \
             require-nots are OR in SBPL and would deny every write: {profile}"
        );
        // the empty-allowlist policy (dev nodes only) keeps the AND
        // combinator too — it is still multi-clause
        let profile = seatbelt_profile(&Policy::fs(Vec::new()));
        assert!(
            profile
                .contains("(deny file-write* (require-all (require-not (subpath \"/dev/null\"))"),
            "empty operator list still needs the AND combinator: {profile}"
        );
        // a bare one-entry deny (dev nodes suppressed for shape check)
        // uses the single-clause form without require-all
        let single = seatbelt_profile(&Policy::fs(vec![PathBuf::from("/only")]))
            .lines()
            .find(|l| l.starts_with("(deny file-write*"))
            .unwrap_or_default()
            .to_string();
        assert!(
            single.contains("(require-all") || single.matches("(require-not").count() == 1,
            "one-clause deny uses the bare form, multi-clause uses require-all: {single}"
        );
        assert!(profile.contains("(deny network*)"), "{profile}");
        // a full-network grant drops the network deny
        let granted = Policy::Fs {
            allow_write: vec![PathBuf::from("/tmp")],
            allow_net: true,
            pass_env: Vec::new(),
            net: NetDomains::default(),
        };
        let profile = seatbelt_profile(&granted);
        assert!(profile.contains("(allow network*)"), "{profile}");
        assert!(!profile.contains("(deny network*)"), "{profile}");
        // empty allowlist: the only writable trees are the enumerated
        // /dev nodes (shell redirections), every operator path denied
        let readonly = Policy::fs(Vec::new());
        let profile = seatbelt_profile(&readonly);
        assert!(
            !profile.contains("(deny file-write*)\n"),
            "no blanket deny line: {profile}"
        );
        assert!(
            profile
                .contains("(deny file-write* (require-all (require-not (subpath \"/dev/null\"))"),
            "all non-/dev writes denied via the scoped deny: {profile}"
        );
        assert!(
            !profile.contains("(subpath \"/work") && !profile.contains("(subpath \"/tmp"),
            "no operator path appears: {profile}"
        );
        // the enumerated /dev surface rides the allowlist like landlock
        let dev_policy = Policy::fs(vec![PathBuf::from("/tmp")]);
        let profile = seatbelt_profile(&dev_policy);
        assert!(
            profile.contains("(subpath \"/dev/null\")"),
            "shell redirections need the enumerated dev nodes: {profile}"
        );
    }

    #[test]
    fn seatbelt_profile_proxy_loopback_allow_follows_deny() {
        // PERM-03: SBPL is last-matching-rule-wins, so the blanket deny
        // must precede the specific loopback allow for the child to reach
        // the loopback proxy while everything else stays denied.
        let restricted = Policy::Fs {
            allow_write: vec![PathBuf::from("/tmp")],
            allow_net: false,
            pass_env: Vec::new(),
            net: NetDomains {
                allow: vec!["api.example.com".to_string()],
                deny: Vec::new(),
            },
        };
        let profile = seatbelt_profile(&restricted);
        let loopback = profile.find("(allow network-outbound (remote ip \"127.0.0.1\"))");
        let deny = profile.find("(deny network*)");
        assert!(
            loopback.is_some(),
            "proxy CONNECT stays reachable: {profile}"
        );
        assert!(deny.is_some(), "everything else stays denied: {profile}");
        assert!(
            deny.unwrap() < loopback.unwrap(),
            "SBPL is last-match-wins: blanket deny must precede the specific loopback allow: {profile}"
        );
        // deny-only policy (proxy active, no allows): same shape
        let deny_only = Policy::Fs {
            allow_write: Vec::new(),
            allow_net: false,
            pass_env: Vec::new(),
            net: NetDomains {
                allow: Vec::new(),
                deny: vec!["evil.example".to_string()],
            },
        };
        let profile = seatbelt_profile(&deny_only);
        assert!(
            profile.contains("(allow network-outbound (remote ip \"127.0.0.1\"))")
                && profile.contains("(deny network*)"),
            "deny-only restriction keeps the proxy reachable: {profile}"
        );
        // unrestricted policy with no grant: the plain blanket deny, no
        // loopback carve-out (no proxy is running)
        let plain = Policy::fs(vec![PathBuf::from("/tmp")]);
        let profile = seatbelt_profile(&plain);
        assert!(profile.contains("(deny network*)"), "{profile}");
        assert!(
            !profile.contains("network-outbound"),
            "no proxy to reach: {profile}"
        );
    }

    #[test]
    fn seatbelt_profile_cannot_be_escaped_by_hostile_paths() {
        // a path containing a quote must not terminate the SBPL string
        // early and inject an unscoped (allow file-write*) — the check
        // refuses the policy before a profile is ever built
        let hostile = Policy::fs(vec![PathBuf::from(
            "/tmp/x\" (allow file-write*) (deny x \"",
        )]);
        assert!(
            seatbelt_profile_check(&hostile).is_err(),
            "hostile path refused"
        );
        // and even if a profile were built from an unchecked policy, the
        // quote is escaped so no directive can be injected: the hostile
        // text stays inside a quoted literal mid-line, and no line is an
        // unscoped standalone `(allow file-write*)`
        let profile = seatbelt_profile(&hostile);
        assert!(
            profile.contains("x\\\" (allow file-write*)"),
            "the injected text stays inside the quoted literal: {profile}"
        );
        let injected = profile
            .lines()
            .any(|line| line.starts_with("(allow file-write*)"));
        assert!(
            !injected,
            "no line may be an unscoped standalone allow: {profile}"
        );
        // backslashes refused too (SBPL escape semantics are undocumented)
        let bs = Policy::fs(vec![PathBuf::from("/tmp/a\\b")]);
        assert!(seatbelt_profile_check(&bs).is_err());
        // ordinary paths pass the check
        let ok = Policy::fs(vec![PathBuf::from("/work/some project/x.bin")]);
        assert!(seatbelt_profile_check(&ok).is_ok());
        // Off policies need no checks and produce an inert profile
        assert!(seatbelt_profile_check(&Policy::Off).is_ok());
        let off = seatbelt_profile(&Policy::Off);
        assert!(
            off.contains("(allow default)") && !off.contains("(deny "),
            "{off}"
        );
    }

