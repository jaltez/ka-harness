/// Sandbox mode (`[sandbox] mode`).
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Mode {
    /// No sandboxing (default).
    #[default]
    Off,
    /// Filesystem allowlist sandbox.
    Fs,
}

/// Domain-scoped network restriction carried by an `fs` policy
/// (PERM-03). Empty lists = no domain restriction: the loopback proxy is
/// inert and children get no proxy environment.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct NetDomains {
    /// Domains the child may reach through the proxy. `*.example.com`
    /// and `example.com` match identically (the entry plus any
    /// subdomain). IP literals must be listed verbatim to pass.
    pub allow: Vec<String>,
    /// Denied domains — they win over `allow`.
    pub deny: Vec<String>,
}

impl NetDomains {
    /// Whether either list carries an entry (proxy-relevant policy).
    pub fn is_restricted(&self) -> bool {
        !self.allow.is_empty() || !self.deny.is_empty()
    }
}

/// The resolved sandbox policy handed to the bash hand.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Policy {
    /// Run the command as-is.
    Off,
    /// Wrap the command in an fs-restricting launcher.
    Fs {
        /// Writable directories (cwd, XDG state/cache, /tmp, plus any
        /// `[sandbox] allow_write` entries and granted expansions).
        allow_write: Vec<PathBuf>,
        /// Network egress permitted (sandbox-expansion grant only; the
        /// base policy always denies where the backend can).
        allow_net: bool,
        /// Env var names passed through to the child (expansion grant;
        /// clearing backends re-set these from the parent environment).
        pass_env: Vec<String>,
        /// Domain-scoped network restriction (PERM-03): when set, the
        /// loopback proxy is the network path and children get proxy
        /// environment injected.
        net: NetDomains,
    },
}

impl Policy {
    /// The stock `fs` policy for an allowlist (no network, no env,
    /// no domain restriction).
    pub fn fs(allow_write: Vec<PathBuf>) -> Self {
        Policy::Fs {
            allow_write,
            allow_net: false,
            pass_env: Vec::new(),
            net: NetDomains::default(),
        }
    }

    /// The domain lists of an fs policy (`None` for `Off`).
    pub fn net_domains(&self) -> Option<&NetDomains> {
        match self {
            Policy::Off => None,
            Policy::Fs { net, .. } => Some(net),
        }
    }
}

/// One sandbox expansion: the exact extra permissions a command needs.
/// Computed deterministically from command analysis (see
/// [`missing_grants`]); applied only after an explicit user ask.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Grants {
    /// Directories the command must be able to write beneath.
    pub write_paths: Vec<PathBuf>,
    /// Network egress for this command.
    pub network: bool,
    /// Env vars to pass through to the child.
    pub env: Vec<String>,
}

impl Grants {
    /// Whether nothing is being asked for.
    pub fn is_empty(&self) -> bool {
        self.write_paths.is_empty() && !self.network && self.env.is_empty()
    }

    /// One-line human summary for ask surfaces.
    pub fn summary(&self) -> String {
        let mut parts: Vec<String> = Vec::new();
        if !self.write_paths.is_empty() {
            let paths: Vec<String> = self
                .write_paths
                .iter()
                .map(|p| p.display().to_string())
                .collect();
            parts.push(format!("write {}", paths.join(", ")));
        }
        if self.network {
            parts.push("network".to_string());
        }
        if !self.env.is_empty() {
            parts.push(format!("env {}", self.env.join(",")));
        }
        parts.join(" · ")
    }

    /// Whether `self` covers everything `other` asks for. A stored write
    /// path covers a requested one only when it is equal to or a parent
    /// of it (`Path::starts_with` compares whole components) — a
    /// narrower stored directory never covers a broader request.
    pub fn covers(&self, other: &Grants) -> bool {
        other
            .write_paths
            .iter()
            .all(|p| self.write_paths.iter().any(|s| p.starts_with(s)))
            && (self.network || !other.network)
            && other.env.iter().all(|e| self.env.contains(e))
    }
}

/// What the active enforcement backend actually denies under `fs`.
/// Grant computation only offers what the backend would truly block —
/// no phantom asks on backends that allow the thing anyway.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Caps {
    /// Network egress is denied. bwrap's `--unshare-all` denies it
    /// outright; under landlock this is best-effort — restricting
    /// network needs Landlock ABI ≥ 4 and never covers UDP.
    pub network_denied: bool,
    /// The child environment is cleared (bwrap `--clearenv`, trampoline).
    pub env_cleared: bool,
}

/// Capabilities of the detected enforcement tool.
pub fn caps() -> Caps {
    match detect_tool() {
        Some(Tool::Firejail) => Caps {
            network_denied: false,
            env_cleared: false,
        },
        // Seatbelt: the profile denies network (unless granted) but does
        // not clear the child environment — env pass-through grants would
        // be phantom asks, so env_cleared stays false.
        Some(Tool::Seatbelt) => Caps {
            network_denied: true,
            env_cleared: false,
        },
        // None only matters under fs, where wrap_command fails closed;
        // report the stricter caps so grant computation stays honest.
        // Landlock's net denial is best-effort (ABI ≥ 4, no UDP), so
        // this flag may pose a grant ask the backend cannot fully
        // enforce — it never silently under-asks.
        Some(Tool::Bubblewrap) | Some(Tool::Landlock) | None => Caps {
            network_denied: true,
            env_cleared: true,
        },
    }
}

/// Directories never offered as write grants: granting a write beneath
/// one of these would effectively unsandbox the filesystem, so commands
/// needing them stay denied (fail-closed).
fn broad_dirs() -> Vec<PathBuf> {
    let mut dirs: Vec<PathBuf> = [
        "/",
        "/bin",
        "/etc",
        "/home",
        "/lib",
        "/lib64",
        "/opt",
        "/root",
        "/sbin",
        "/srv",
        "/usr",
        "/var",
        "/Users",
        r"C:\",
        r"C:\Windows",
    ]
    .iter()
    .map(PathBuf::from)
    .collect();
    if let Ok(home) = std::env::var("HOME") {
        dirs.push(PathBuf::from(home));
    }
    dirs
}

/// The only `/dev` entries the landlock backend grants writes to —
/// an enumerated surface matching what builds need, instead of the
/// whole host `/dev` (bwrap's `--dev` is a fresh tmpfs, so wholesale
/// `/dev` there was never the parity). `/dev/shm` is intentionally
/// excluded so sandboxed children cannot persist files outside
/// `allow_write` via host shared memory.
const DEV_NODES: &[&str] = &[
    "/dev/null",
    "/dev/zero",
    "/dev/full",
    "/dev/random",
    "/dev/urandom",
];

/// Resolve a writable-allowlist entry to its real on-disk target:
/// canonicalize the nearest existing ancestor, then re-append the
/// not-yet-created remainder (grant dirs may not exist yet). Both
/// enforcement backends bind/attach the resolved inode, so a symlink
/// spelling must never widen what the rule actually covers: if the
/// resolved path IS a broad root (`/`, `$HOME`, `/etc`, …) or sits
/// above one, the entry is refused — fail closed.
pub(crate) fn resolve_writable(p: &Path) -> Result<PathBuf, String> {
    let mut prefix = p.to_path_buf();
    let mut suffix: Vec<std::ffi::OsString> = Vec::new();
    let canonical = loop {
        match std::fs::canonicalize(&prefix) {
            Ok(c) => break Some(c),
            Err(_) => match (prefix.parent(), prefix.file_name()) {
                (Some(parent), Some(name)) => {
                    suffix.push(name.to_os_string());
                    prefix = parent.to_path_buf();
                }
                _ => break None,
            },
        }
    };
    let Some(mut resolved) = canonical else {
        return Err(format!(
            "sandbox: cannot resolve writable path {} — refusing",
            p.display()
        ));
    };
    for seg in suffix.into_iter().rev() {
        resolved.push(seg);
    }
    // `b.starts_with(&resolved)` covers both equality (resolved IS the
    // broad root) and resolved being a proper ancestor of it (a grant
    // at or above `$HOME`, `/`, … unsandboxes everything beneath).
    // Broad roots may themselves be symlink spellings ($HOME under an
    // automount), so canonicalized forms join the comparison — else a
    // grant resolving to the real home slips past the lexical entries.
    let broad = broad_dirs();
    let broad_resolved: Vec<PathBuf> = broad
        .iter()
        .filter_map(|b| std::fs::canonicalize(b).ok())
        .collect();
    if let Some(b) = broad
        .iter()
        .chain(broad_resolved.iter())
        .find(|b| b.starts_with(&resolved))
    {
        return Err(format!(
            "sandbox: writable path {} resolves to {}, which is or contains the broad \
             root {} — refusing",
            p.display(),
            resolved.display(),
            b.display()
        ));
    }
    Ok(resolved)
}

/// Lexically normalize a path (no filesystem access): resolve `.`/`..`,
/// make relative paths absolute against `cwd`, expand a leading `~` or
/// `~/` to `$HOME` (a `~user` prefix is left alone). Sandbox grant
/// matching is prefix-based and needs a canonical spelling even for
/// not-yet-existing targets.
fn normalize(p: &Path, cwd: &Path) -> PathBuf {
    let text = p.to_string_lossy();
    let expanded: PathBuf = if text == "~" {
        std::env::var("HOME")
            .map(PathBuf::from)
            .unwrap_or_else(|_| p.to_path_buf())
    } else if let Some(rest) = text.strip_prefix("~/") {
        std::env::var("HOME")
            .map(|h| PathBuf::from(h).join(rest))
            .unwrap_or_else(|_| p.to_path_buf())
    } else {
        // `~user/…` is another user's home: mapping it under $HOME
        // would grant the wrong tree, so it stays unexpanded (and
        // therefore ungrantable — fail-closed)
        p.to_path_buf()
    };
    let abs = if expanded.is_absolute() {
        expanded
    } else {
        cwd.join(&expanded)
    };
    let mut out = PathBuf::new();
    for comp in abs.components() {
        match comp {
            std::path::Component::CurDir => {}
            std::path::Component::ParentDir => {
                // never pop past the root: `/w/../../etc` must stay
                // absolute (`/etc`), not collapse to a relative path
                // that would bind the wrong subtree
                if out.parent().is_some() {
                    out.pop();
                }
            }
            other => out.push(other),
        }
    }
    out
}

/// Compute what `command inputs` need beyond `policy`. Inputs come from
/// bash command analysis (redirection targets, env assignments,
/// network-tool detection); the result is deterministic for a given
/// command line AND parent environment — the env pass-through check
/// reads the live environment and broad-dir rejection reads `$HOME`.
/// Non-grantable needs (writes beneath broad dirs like `/` or `$HOME`
/// itself, env vars unset in the parent) are silently left out: the
/// command will fail rather than over-ask.
pub fn missing_grants(
    policy: &Policy,
    cwd: &Path,
    redirect_targets: &[String],
    env_vars: &[String],
    wants_net: bool,
) -> Grants {
    let Policy::Fs {
        allow_write,
        allow_net,
        pass_env,
        net,
    } = policy
    else {
        return Grants::default();
    };
    let caps = caps();
    let mut grants = Grants::default();
    let broad = broad_dirs();
    for target in redirect_targets {
        let lexical = normalize(Path::new(target), cwd);
        // enforcement binds/attaches the RESOLVED inode, so grant asks
        // must point at the resolved target, not the lexical spelling;
        // an unresolvable target stays denied (fail-closed)
        let resolved = resolve_writable(&lexical).ok();
        // Path::starts_with compares whole components, so `/tmpfoo`
        // is NOT inside `/tmp` — no string-prefix escape here
        let covered = |p: &Path| allow_write.iter().any(|a| p.starts_with(a));
        if resolved.as_ref().is_some_and(|r| covered(r)) || covered(&lexical) {
            continue;
        }
        // the target is a file the command writes; the sandbox grants
        // directories, so the grant is its parent (resolved spelling)
        let base = resolved.as_deref().unwrap_or(&lexical);
        let Some(parent) = base.parent() else {
            continue;
        };
        let lexical_parent = lexical.parent();
        // canonicalized broad spellings too: a redirect into the real
        // home behind a symlinked $HOME must stay denied
        let broad_resolved: Vec<PathBuf> = broad
            .iter()
            .filter_map(|b| std::fs::canonicalize(b).ok())
            .collect();
        let is_broad = |p: &Path| {
            broad.iter().any(|b| p == b.as_path())
                || broad_resolved.iter().any(|b| p == b.as_path())
        };
        if parent.as_os_str().is_empty() || is_broad(parent) || lexical_parent.is_some_and(is_broad)
        {
            continue; // not grantable without unsandboxing — stays denied
        }
        // hidden dirs directly under $HOME (.ssh, .gnupg, .config …)
        // are persistence/config territory: never offered as a write
        // grant, same refusal class as $HOME itself — checked on both
        // spellings so a symlinked $HOME cannot sneak one through
        if let Ok(home) = std::env::var("HOME") {
            let home_resolved = std::fs::canonicalize(&home).ok();
            let hidden = |p: &Path| {
                p.parent().is_some_and(|gp| {
                    gp == Path::new(&home) || home_resolved.as_deref() == Some(gp)
                }) && p
                    .file_name()
                    .and_then(|n| n.to_str())
                    .is_some_and(|n| n.starts_with('.'))
            };
            if hidden(parent) || lexical_parent.is_some_and(hidden) {
                continue;
            }
        }
        if !grants
            .write_paths
            .iter()
            .any(|p: &PathBuf| p == parent || parent.starts_with(p))
        {
            grants.write_paths.push(parent.to_path_buf());
        }
    }
    if caps.env_cleared {
        for name in env_vars {
            if pass_env.contains(name) || grants.env.contains(name) {
                continue;
            }
            // only vars that actually carry a value in the parent env —
            // asking to pass through an unset var is noise
            if std::env::var(name).map(|v| !v.is_empty()).unwrap_or(false) {
                grants.env.push(name.clone());
            }
        }
    }
    // PERM-03: under a domain-restricted policy the proxy IS the
    // network story — offering a full-network expansion grant would
    // widen past the standing config (fail-closed: to change scope,
    // edit [sandbox], don't grant per command)
    grants.network = wants_net && caps.network_denied && !*allow_net && !net.is_restricted();
    grants
}

/// Apply grants onto a policy (the per-call or live expansion).
pub fn apply_grants(policy: &Policy, grants: &Grants) -> Policy {
    match policy {
        Policy::Off => Policy::Off,
        Policy::Fs {
            allow_write,
            allow_net,
            pass_env,
            net,
        } => {
            let mut allow = allow_write.clone();
            for p in &grants.write_paths {
                if !allow.contains(p) {
                    allow.push(p.clone());
                }
            }
            let mut env = pass_env.clone();
            for e in &grants.env {
                if !env.contains(e) {
                    env.push(e.clone());
                }
            }
            Policy::Fs {
                allow_write: allow,
                allow_net: *allow_net || grants.network,
                pass_env: env,
                net: net.clone(),
            }
        }
    }
}

/// Sandbox configuration table (`[sandbox]`).
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields, default)]
pub struct SandboxConfig {
    /// `"off"` (default) or `"fs"`.
    pub mode: Option<String>,
    /// Extra writable directories on top of the default allowlist
    /// (cwd, /tmp, XDG state/cache). `[sandbox] allow_write` in the
    /// project layer is where an "always" expansion grant persists.
    pub allow_write: Vec<String>,
    /// PERM-03: domains bash children may reach through the loopback
    /// proxy. `*.example.com` / `example.com` both match the domain and
    /// its subdomains; IP literals must be listed verbatim. Non-empty
    /// ⇒ children get proxy environment injected and the loopback
    /// proxy is live for the policy's lifetime.
    pub net_allow_domains: Vec<String>,
    /// PERM-03: denied domains (they win over `net_allow_domains`).
    pub net_deny_domains: Vec<String>,
}

/// The writable-directory allowlist for `cwd`.
pub fn allowlist_for(cwd: &Path) -> Vec<PathBuf> {
    let mut allow = vec![cwd.to_path_buf(), PathBuf::from("/tmp")];
    let state = std::env::var("XDG_STATE_HOME")
        .map(PathBuf::from)
        .or_else(|_| std::env::var("HOME").map(|h| PathBuf::from(h).join(".local/state")));
    let cache = std::env::var("XDG_CACHE_HOME")
        .map(PathBuf::from)
        .or_else(|_| std::env::var("HOME").map(|h| PathBuf::from(h).join(".cache")));
    if let Ok(p) = state {
        allow.push(p);
    }
    if let Ok(p) = cache {
        allow.push(p);
    }
    allow
}

/// Resolve config → policy.
///
/// Default-allowlist entries (cwd, /tmp, XDG state/cache) that resolve to
/// an ancestor of a protected broad root are DROPPED, not fatal: the
/// defaults must never brick every sandboxed command (a data root under
/// /tmp with `$HOME` inside it is a real layout — containers, test
/// harnesses), and dropping only tightens the sandbox. Explicit
/// `[sandbox] allow_write` entries keep failing hard: the operator asked
/// for exactly that path.
pub fn policy_from_config(cfg: &SandboxConfig, cwd: &Path) -> Result<Policy, String> {
    let mode = cfg.mode.as_deref().unwrap_or("off");
    match mode {
        "off" => Ok(Policy::Off),
        "fs" => {
            let mut allow: Vec<PathBuf> = allowlist_for(cwd)
                .into_iter()
                .filter(|d| resolve_writable(d).is_ok())
                .collect();
            for extra in &cfg.allow_write {
                let path = normalize(Path::new(extra), cwd);
                if !allow.contains(&path) {
                    allow.push(path);
                }
            }
            Ok(Policy::Fs {
                allow_write: allow,
                allow_net: false,
                pass_env: Vec::new(),
                net: NetDomains {
                    allow: cfg.net_allow_domains.clone(),
                    deny: cfg.net_deny_domains.clone(),
                },
            })
        }
        other => Err(format!(
            "[sandbox] mode: unknown value {other:?} (expected \"off\" or \"fs\")"
        )),
    }
}

/// Which sandbox engine is available, if any. Detection order:
/// bubblewrap, then in-kernel landlock (linux only, no external binary
/// needed), then firejail, then macOS Seatbelt (`sandbox-exec`,
/// deprecated by Apple but functional). On Windows nothing is ever
/// detected — sandboxing is unsupported there and fs mode fails closed.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Tool {
    Bubblewrap,
    Firejail,
    /// In-kernel LSM enforcement via the self re-exec trampoline.
    Landlock,
    /// macOS Seatbelt via `/usr/bin/sandbox-exec -p <profile>` (PERM-04). The
    /// variant exists on every OS so downstream matches don't need
    /// cfg-gating; detection only ever returns it on macOS.
    Seatbelt,
}

/// Pure backend selection logic — testable for every OS regardless of the
/// host running the test suite. On Windows (`is_windows == true`) this
/// always returns `None` (fail closed), even if a binary named `bwrap` or
/// `firejail` happens to be on `PATH`. On non-Windows hosts the priority
/// order is: `bwrap` → `landlock` → `firejail` → `seatbelt`.
#[must_use]
pub fn detect_tool_for_os(
    is_windows: bool,
    has_bwrap: bool,
    has_landlock: bool,
    has_firejail: bool,
    has_seatbelt: bool,
) -> Option<Tool> {
    if is_windows {
        return None;
    }
    if has_bwrap {
        return Some(Tool::Bubblewrap);
    }
    if has_landlock {
        return Some(Tool::Landlock);
    }
    if has_firejail {
        return Some(Tool::Firejail);
    }
    if has_seatbelt {
        return Some(Tool::Seatbelt);
    }
    None
}

pub fn detect_tool() -> Option<Tool> {
    *DETECTED
}

/// Why detection found nothing (empty string when a backend exists).
/// Windows names the platform — `mode = "fs"` there is a hard, honest
/// refusal, not a missing-binary accident.
pub fn detect_reason() -> &'static str {
    if detect_tool().is_some() {
        return "";
    }
    #[cfg(target_os = "windows")]
    {
        "windows sandboxing unsupported — no sandbox backend exists; \
         [sandbox] mode \"fs\" fails closed"
    }
    #[cfg(target_os = "macos")]
    {
        "no sandbox backend: bwrap/firejail missing and /usr/bin/sandbox-exec absent — \
         fail-closed"
    }
    #[cfg(not(any(target_os = "windows", target_os = "macos")))]
    {
        "no sandbox backend: bwrap/firejail missing and kernel landlock unavailable — \
         fail-closed"
    }
}

/// The probes fork bwrap/firejail and create a landlock ruleset fd —
/// `wrap_command` runs per bash call, so resolve once per process.
/// On Windows detection is unconditionally `None` (fail closed) — never
/// probe `bwrap`/`firejail` on `PATH`.
static DETECTED: std::sync::LazyLock<Option<Tool>> = std::sync::LazyLock::new(|| {
    #[cfg(target_os = "windows")]
    {
        detect_tool_for_os(true, false, false, false, false)
    }
    #[cfg(not(target_os = "windows"))]
    {
        let probe_bin = |bin: &str| {
            std::process::Command::new(bin)
                .arg("--version")
                .stdout(std::process::Stdio::null())
                .stderr(std::process::Stdio::null())
                .status()
                .map(|s| s.success())
                .unwrap_or(false)
        };
        if probe_bin("bwrap") {
            return detect_tool_for_os(false, true, false, false, false);
        }
        #[cfg(target_os = "linux")]
        if landlock_supported() {
            return detect_tool_for_os(false, false, true, false, false);
        }
        if probe_bin("firejail") {
            return detect_tool_for_os(false, false, false, true, false);
        }
        // PERM-04: Seatbelt ships with macOS — presence of sandbox-exec is
        // the only probe needed. Sits last in the chain: bwrap, landlock,
        // and firejail stay preferred where installed.
        #[cfg(target_os = "macos")]
        if Path::new("/usr/bin/sandbox-exec").exists() {
            return detect_tool_for_os(false, false, false, false, true);
        }
        None
    }
});
/// Whether the kernel can create landlock rulesets. Probe only:
/// `Ruleset::create()` issues `landlock_create_ruleset(2)` and returns
/// an (immediately dropped) fd — nothing is enforced on the caller;
/// enforcement happens later inside the trampoline process. Preferred
/// over reading `/sys/kernel/security/lsm`, which is often hidden
/// (e.g. WSL2) even on landlock-capable kernels.
#[cfg_attr(not(target_os = "linux"), allow(dead_code))]
fn landlock_supported() -> bool {
    #[cfg(target_os = "linux")]
    {
        use landlock::{ABI, AccessFs, Ruleset, RulesetAttr};
        Ruleset::default()
            .handle_access(AccessFs::from_read(ABI::V1))
            .and_then(|r| r.create().map(|_| ()))
            .is_ok()
    }
    #[cfg(not(target_os = "linux"))]
    {
        false
    }
}

/// The trampoline policy JSON: what `ka-sandbox-exec` enforces. Shipped
/// shape (an object with `writable`/`net`/`env`); only ever exchanged
/// between `wrap_command` and the hidden subcommand of the same binary.
#[derive(Debug, Serialize, Deserialize)]
struct TrampolinePolicy {
    writable: Vec<PathBuf>,
    net: bool,
    env: Vec<String>,
    /// PERM-03: TCP ports the child may CONNECT to even with network
    /// otherwise denied — the loopback proxy's port, so a domain-scoped
    /// policy keeps working on landlock (port granularity is the finest
    /// landlock offers; any address on that port is reachable).
    #[serde(default)]
    net_ports: Vec<u16>,
    /// PERM-03: explicit proxy env pairs (name, value) re-set inside the
    /// trampoline child — the dynamic proxy URL is not in the ka process
    /// environment, so the name-list `env` pass-through cannot carry it.
    #[serde(default)]
    env_pairs: Vec<(String, String)>,
}

/// Build the wrapped argv for `command` under the given policy.
/// `Err` = fail closed (no enforcement tool available).
pub fn wrap_command(policy: &Policy, command: &str, cwd: &Path) -> Result<Vec<String>, String> {
    match policy {
        Policy::Off => Ok(vec!["sh".into(), "-c".into(), command.into()]),
        Policy::Fs {
            allow_write,
            allow_net,
            pass_env,
            net,
        } => {
            // both backends bind/attach the RESOLVED inode: resolve
            // every writable entry up front and refuse (fail closed)
            // any that lands on or above a broad root via symlink
            let resolved: Vec<PathBuf> = allow_write
                .iter()
                .map(|d| resolve_writable(d.as_path()))
                .collect::<Result<_, _>>()?;
            // PERM-03: a domain-restricted policy needs its loopback
            // proxy reachable. Under landlock the child may CONNECT to
            // exactly the proxy's port; bwrap shares the network stack
            // (it cannot scope ports — raw sockets can bypass the proxy
            // env filter; see proxy module doc for the honest matrix).
            // The proxy env vars ride the BACKEND, not just the spawned
            // process: env-clearing backends (bwrap --clearenv, the
            // trampoline) would otherwise wipe them before the child
            // ever sees them. The URL is a loopback address — never
            // secret, so --setenv argv exposure is fine.
            let restricted = net.is_restricted();
            let (proxy_vars, proxy_port) = if restricted {
                let env = proxy::proxy_env(policy)?
                    .ok_or_else(|| "sandbox proxy: restricted policy without proxy".to_string())?;
                let port = env.addr.port();
                (env.vars(), Some(port))
            } else {
                (Vec::new(), None)
            };
            let net_ports = if restricted && !*allow_net {
                proxy_port.map(|p| vec![p]).unwrap_or_default()
            } else {
                Vec::new()
            };
            match detect_tool() {
                Some(Tool::Bubblewrap) => {
                    let mut argv = vec![
                        "bwrap".into(),
                        "--unshare-all".into(),
                        "--die-with-parent".into(),
                        "--new-session".into(),
                        "--ro-bind".into(),
                        "/".into(),
                        "/".into(),
                        "--dev".into(),
                        "/dev".into(),
                        "--proc".into(),
                        "/proc".into(),
                    ];
                    if *allow_net || restricted {
                        // ordered after --unshare-all: re-share the network
                        // stack — for the expansion grant (full net) or so
                        // the domain-restricted child can reach the loopback
                        // proxy at all
                        argv.push("--share-net".into());
                    }
                    for dir in &resolved {
                        argv.push("--bind".into());
                        argv.push(dir.to_string_lossy().into_owned());
                        argv.push(dir.to_string_lossy().into_owned());
                    }
                    argv.push("--clearenv".into());
                    // --setenv values ride bwrap's own argv, so they are
                    // visible in /proc/<pid>/cmdline to anyone who can read
                    // it — never expand the pass-through with secret-bearing
                    // env names (the proxy URL is a loopback address: fine)
                    for name in pass_env {
                        if let Ok(value) = std::env::var(name) {
                            argv.push("--setenv".into());
                            argv.push(name.clone());
                            argv.push(value);
                        }
                    }
                    // PERM-03: proxy env survives --clearenv into the child
                    for (name, value) in &proxy_vars {
                        argv.push("--setenv".into());
                        argv.push(name.clone());
                        argv.push(value.clone());
                    }
                    argv.push("sh".into());
                    argv.push("-c".into());
                    argv.push(command.into());
                    Ok(argv)
                }
                Some(Tool::Firejail) => {
                    // firejail keeps the environment and (without --net=none)
                    // the network: only the write allowlist applies
                    let mut argv = vec![
                        "firejail".into(),
                        "--quiet".into(),
                        "--private=.".into(),
                        "--read-only=/".into(),
                    ];
                    for dir in &resolved {
                        argv.push(format!("--whitelist={}", dir.display()));
                    }
                    // PERM-03: firejail keeps the environment, but the ka
                    // process itself has no proxy vars — set them explicitly
                    for (name, value) in &proxy_vars {
                        argv.push(format!("--env={name}={value}"));
                    }
                    argv.push("--".into());
                    argv.push("sh".into());
                    argv.push("-c".into());
                    argv.push(command.into());
                    let _ = cwd;
                    Ok(argv)
                }
                Some(Tool::Landlock) => {
                    // self re-exec trampoline: the sandboxed command becomes
                    // `<ka> ka-sandbox-exec <policy-json> -- <argv…>`;
                    // the hidden subcommand applies the landlock ruleset to
                    // itself, then execs the real argv (the workspace forbids
                    // `unsafe`, so no Command::pre_exec). The policy JSON is
                    // the resolved allow_write list plus an enumerated /dev
                    // surface (bwrap's --dev is a fresh tmpfs, so granting
                    // the host /dev wholesale was never the parity) plus
                    // the net/env expansion grants.
                    let mut writable = resolved;
                    writable.extend(
                        DEV_NODES
                            .iter()
                            .filter(|p| Path::new(p).exists())
                            .map(|p| PathBuf::from(*p)),
                    );
                    let policy = serde_json::to_string(&TrampolinePolicy {
                        writable,
                        net: *allow_net,
                        env: pass_env.clone(),
                        net_ports,
                        env_pairs: proxy_vars,
                    })
                    .map_err(|e| format!("sandbox policy: {e}"))?;
                    // readlink(/proc/self/exe) once per process, not per call
                    static EXE: std::sync::LazyLock<Result<PathBuf, String>> =
                        std::sync::LazyLock::new(|| {
                            std::env::current_exe().map_err(|e| format!("sandbox trampoline: {e}"))
                        });
                    let exe = EXE.as_ref().map_err(Clone::clone)?;
                    Ok(vec![
                        exe.to_string_lossy().into_owned(),
                        TRAMPOLINE_ARG.into(),
                        policy,
                        "--".into(),
                        "sh".into(),
                        "-c".into(),
                        command.into(),
                    ])
                }
                Some(Tool::Seatbelt) => {
                    // PERM-04: macOS Seatbelt. `sandbox-exec` has been
                    // deprecated by Apple (since 10.13) but remains the
                    // OS's own sandboxing mechanism and still works; when
                    // Apple removes it, detection stops finding it and fs
                    // fails closed like any other missing backend. The
                    // arm is compiled everywhere (detection only ever
                    // returns Seatbelt on macOS) so the match stays
                    // exhaustive without cfg-gating. The profile is
                    // generated by the pure `seatbelt_profile`
                    // (testable on every OS) from the RESOLVED allowlist —
                    // same symlink-parity rules as the other backends.
                    let resolved_policy = Policy::Fs {
                        allow_write: resolved.clone(),
                        allow_net: *allow_net,
                        pass_env: Vec::new(),
                        net: net.clone(),
                    };
                    seatbelt_profile_check(&resolved_policy)?;
                    let profile = seatbelt_profile_with_port(&resolved_policy, proxy_port);
                    let _ = cwd;
                    Ok(seatbelt_argv(&profile, command))
                }
                None => Err(format!(
                    "sandbox: mode \"fs\" requires an enforcement backend and none is \
                     available on this host ({}) — refusing to run unsandboxed",
                    detect_reason()
                )),
            }
        }
    }
}

/// Characters a Seatbelt profile string literal can carry without risk.
/// Anything else in a writable path would either break the profile
/// syntax (sandbox-exec then refuses = fail closed) or, with an embedded
/// quote, could terminate the string early and inject profile directives
/// — the check refuses instead (fail closed with a clear operator error).
fn seatbelt_path_is_safe(p: &Path) -> bool {
    p.to_str().is_some_and(|s| {
        s.chars()
            .all(|c| c.is_ascii_alphanumeric() || " /._-+@".contains(c))
    })
}

/// Validate that `policy`'s writable entries are expressible in a
/// Seatbelt profile. Called before profile generation so a hostile path
/// fails the command with a named reason instead of a parser error.
pub fn seatbelt_profile_check(policy: &Policy) -> Result<(), String> {
    let Policy::Fs { allow_write, .. } = policy else {
        return Ok(());
    };
    for dir in allow_write {
        if !seatbelt_path_is_safe(dir) {
            return Err(format!(
                "sandbox: writable path {} contains characters the Seatbelt profile \
                 cannot express — refusing (fail closed)",
                dir.display()
            ));
        }
    }
    Ok(())
}

/// Quote a path for the SBPL string literal. Only ever called after
/// [`seatbelt_profile_check`]; the escaping is defense in depth so a
/// caller-side regression can never inject a directive.
fn seatbelt_quote(p: &Path) -> String {
    p.to_string_lossy()
        .replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('\n', "\\n")
        .replace('\r', "\\r")
}

/// Generate the Seatbelt profile for `policy` — a PURE function so it is
/// testable on every OS (the profile is only executed on macOS).
///
/// SBPL is **last-matching-rule-wins**: later matching rules override
/// earlier broader rules. For filesystem writes, the explicit
/// `(allow file-write* (subpath …))` is followed by a scoped
/// `(deny file-write* (require-all (require-not (subpath …)) …))` that
/// matches only paths OUTSIDE the allowlist. For domain-scoped network,
/// `(deny network*)` is emitted FIRST and the specific loopback
/// `(allow network-outbound (remote ip …))` is emitted AFTER so the
/// loopback proxy remains reachable while all other network access stays
/// denied. The enumerated `/dev` nodes ride the allowlist like the
/// landlock backend (shells need `/dev/null` for redirections). `Off`
/// policies get a no-op profile (everything allowed) — callers never
/// wrap `Off` runs.
pub fn seatbelt_profile(policy: &Policy) -> String {
    seatbelt_profile_with_port(policy, None)
}

/// Generate the Seatbelt profile for `policy`, optionally scoping the
/// domain-proxy loopback exception to a specific `proxy_port`.
pub fn seatbelt_profile_with_port(policy: &Policy, proxy_port: Option<u16>) -> String {
    // Off policies are never wrapped; if one reaches here the profile is
    // inert (allow everything, deny nothing)
    let (allow_write, allow_net, net) = match policy {
        Policy::Fs {
            allow_write,
            allow_net,
            net,
            ..
        } => (allow_write.clone(), *allow_net, net.clone()),
        Policy::Off => return "(version 1)\n(allow default)\n".to_string(),
    };
    let mut profile = String::from(
        "; ka fs sandbox (PERM-04) — allow-by-default base with scoped denies;\n\
         ; SBPL is last-matching-rule-wins: specific allows follow broader denies\n\
         (version 1)\n(allow default)\n(allow file-read*)\n",
    );
    // enumerated /dev surface: pure parity with the landlock trampoline
    // (no exists() checks — the profile stays a pure function)
    let mut writes: Vec<String> = allow_write
        .iter()
        .map(|p| p.to_string_lossy().into_owned())
        .collect();
    for node in DEV_NODES {
        writes.push((*node).to_string());
    }
    if writes.is_empty() {
        profile.push_str("(deny file-write*)\n");
    } else {
        profile.push_str("(allow file-write*");
        for dir in &writes {
            profile.push_str(&format!(
                " (subpath \"{}\")",
                seatbelt_quote(Path::new(dir))
            ));
        }
        profile.push_str(")\n");
        // SBPL combines sibling `(require-not …)` filters as OR (any
        // match satisfies the filter), which would deny ALL writes once
        // more than one carve-out exists. `require-all` is the real AND:
        // the deny only fires when the path matches none of the
        // allowlist subpaths. A single entry keeps the bare form.
        if writes.len() == 1 {
            profile.push_str(&format!(
                "(deny file-write* (require-not (subpath \"{}\")))\n",
                seatbelt_quote(Path::new(&writes[0]))
            ));
        } else {
            profile.push_str("(deny file-write* (require-all");
            for dir in &writes {
                profile.push_str(&format!(
                    " (require-not (subpath \"{}\"))",
                    seatbelt_quote(Path::new(dir))
                ));
            }
            profile.push_str("))\n");
        }
    }
    if allow_net {
        profile.push_str("(allow network*)\n");
    } else if net.is_restricted() {
        // PERM-03: SBPL is last-matching-rule-wins. Emit the blanket
        // `(deny network*)` FIRST, then the specific loopback allow
        // AFTER so the child can reach the loopback proxy while all
        // other network traffic stays denied.
        profile.push_str("(deny network*)\n");
        if let Some(port) = proxy_port {
            profile.push_str(&format!(
                "(allow network-outbound (remote ip \"127.0.0.1:{port}\"))\n"
            ));
        } else {
            profile.push_str("(allow network-outbound (remote ip \"127.0.0.1\"))\n");
        }
    } else {
        profile.push_str("(deny network*)\n");
    }
    profile
}

/// The `/usr/bin/sandbox-exec` argv shape for a profile + command — pure
/// so the argv contract is testable on every OS.
#[must_use]
pub fn seatbelt_argv(profile: &str, command: &str) -> Vec<String> {
    vec![
        "/usr/bin/sandbox-exec".to_string(),
        "-p".to_string(),
        profile.to_string(),
        "sh".to_string(),
        "-c".to_string(),
        command.to_string(),
    ]
}

