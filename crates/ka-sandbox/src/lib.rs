    #[test]
    fn wrap_command_injects_proxy_env_through_the_backend() {
        // PERM-03: the proxy vars must reach the CHILD through the
        // backend (env-clearing backends wipe the process env), and a
        // restricted policy shares the network so the proxy is reachable.
        let _guard = proxy::tests::PROXY_TEST_LOCK
            .lock()
            .unwrap_or_else(|p| p.into_inner());
        if detect_tool().is_none() {
            return; // no backend: wrap fails closed before argv exists
        }
        let policy = Policy::Fs {
            allow_write: vec![PathBuf::from("/tmp")],
            allow_net: false,
            pass_env: Vec::new(),
            net: NetDomains {
                allow: vec!["example.com".into()],
                deny: Vec::new(),
            },
        };
        let argv = wrap_command(&policy, "true", Path::new("/tmp")).unwrap();
        match detect_tool() {
            Some(Tool::Bubblewrap) => {
                assert!(
                    argv.contains(&"--share-net".to_string()),
                    "restricted policy shares net so the child can reach the proxy: {argv:?}"
                );
                let setenv = |name: &str| {
                    argv.windows(3)
                        .find(|w| w[0] == "--setenv" && w[1] == name)
                        .map(|w| w[2].clone())
                };
                let https = setenv("HTTPS_PROXY").expect("bwrap setenv carries HTTPS_PROXY");
                assert!(https.starts_with("http://127.0.0.1:"), "{https}");
                assert_eq!(
                    setenv("HTTPS_PROXY"),
                    setenv("https_proxy"),
                    "both cases injected"
                );
                assert_eq!(
                    setenv("NO_PROXY").as_deref(),
                    Some(proxy::NO_PROXY_LOOPBACK)
                );
            }
            Some(Tool::Firejail) => {
                assert!(
                    argv.iter()
                        .any(|a| a.starts_with("--env=HTTPS_PROXY=http://127.0.0.1:")),
                    "firejail --env carries the proxy: {argv:?}"
                );
            }
            Some(Tool::Landlock) => {
                let parsed: serde_json::Value =
                    serde_json::from_str(&argv[2]).expect("trampoline policy JSON");
                let ports = parsed["net_ports"].as_array().expect("net_ports array");
                assert_eq!(
                    ports.len(),
                    1,
                    "the proxy port is the one allowed port: {parsed}"
                );
                assert!(ports[0].as_u64().unwrap_or(0) > 0);
                let pairs = parsed["env_pairs"].as_array().expect("env_pairs array");
                assert!(
                    pairs.iter().any(|p| p[0] == "HTTPS_PROXY"
                        && p[1].as_str().unwrap_or("").starts_with("http://127.0.0.1:")),
                    "trampoline env_pairs carry the proxy: {parsed}"
                );
            }
            Some(Tool::Seatbelt) => {
                // sandbox-exec inherits the wrapping process env: the
                // hand-level injection covers it, the profile needs no env
                assert_eq!(argv[0], "/usr/bin/sandbox-exec", "{argv:?}");
            }
            None => {}
        }
        // leave the process-global proxy off for the other tests
        assert!(proxy_env(&Policy::Off).unwrap().is_none());
    }
